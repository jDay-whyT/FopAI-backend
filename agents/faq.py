_compiled: list[tuple[re.Pattern[str], str]] = [
    (re.compile(p), ans) for p, ans in _RULES
]


def lookup(text: str) -> str | None:
    """Return pre-baked answer if text matches a known FAQ, else None."""
    lower = text.lower()
    for pattern, answer in _compiled:
        if pattern.search(lower):
            return answer
    return None
